// ステージ定義。最大サイズのプレイヤーが必須走路を通過できるよう床上 3 タイルを空ける。
// 行は上から下へ。'.' = 空、'#' = 地面、'P' = プレイヤースポーン、'G' = クロックビーコン、
// 'E' = 巻きネジ障害機 (真下が '#' 必須)、'C' = 歯車片、'M' = ぜんまい、
// 'F' = パルスコア、'S' = クロノクリスタル (いずれも空中配置可)。
// レイアウトの設計: 段差 N=1/2/3 の 3 段差 + 隙間 2 箇所 + ゴール (床上 N=2)。
// ジャンプ高さの理論最大値 ≒ 4 タイル弱なので N=3 まで。

export type TileChar = '.' | '#' | 'P' | 'G' | 'E' | 'C' | 'M' | 'F' | 'S';

export interface CriticalPathSegment {
  readonly fromCol: number;
  readonly toCol: number;
  readonly supportRow: number;
}

export interface StageDifficultyTarget {
  readonly role: 'intro' | 'intermediate' | 'final';
  readonly minimumScore: number;
}

export interface StageDefinition {
  readonly id: string;
  readonly cols: number;
  readonly rows: number;
  readonly tiles: readonly string[];
  readonly criticalPath: readonly CriticalPathSegment[];
  readonly difficulty: StageDifficultyTarget;
}

